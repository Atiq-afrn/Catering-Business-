  /// Fetch translation key with fallback
  static String tr(String key, {String langCode = 'en', Map<String, String>? params}) {
    String value = key;
    if (_localizedValues.containsKey(langCode) &&
        _localizedValues[langCode]!.containsKey(key)) {
      value = _localizedValues[langCode]![key]!;
    } else if (_localizedValues['en']!.containsKey(key)) {
      value = _localizedValues['en']![key]!;
    }

    if (params != null) {
      params.forEach((paramKey, paramVal) {
        value = value.replaceAll('{$paramKey}', paramVal);
      });
    }

    return value;
  }
